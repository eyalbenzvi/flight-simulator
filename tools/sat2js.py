#!/usr/bin/env python3
"""The real colour of the land: NASA / USGS Landsat (the WELD annual true-colour composite of 2000, public domain, through NASA GIBS) over the map
window, 2048 x 4096 pixels, about 130 m of real ground each -> src/sat.js.

The terrain shader uses it as the ground's base tint under all its own detail, so deserts, hills, valleys and farmland have their true hues and
patterns. Water pixels (the sea, the two lakes) are filled from the nearest land, so no blue bleeds onto the shore where the game's coast differs
from the real one. Small devices scale the picture down when they load it.

  python3 tools/sat2js.py
"""
import base64, io, os, urllib.request
import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); CACHE = os.path.join(ROOT, 'raw', 'sat'); os.makedirs(CACHE, exist_ok=True)
W, H = 2048, 4096
f = os.path.join(CACHE, 'landsat2000.jpg')
if not os.path.exists(f):
    url = ('https://gibs.earthdata.nasa.gov/wms/epsg4326/best/wms.cgi?SERVICE=WMS&REQUEST=GetMap&VERSION=1.3.0&LAYERS=Landsat_WELD_CorrectedReflectance_TrueColor_Global_Annual'
           f'&CRS=EPSG:4326&BBOX=29.2,33.6,33.6,36.4&WIDTH={W}&HEIGHT={H}&FORMAT=image/jpeg&TIME=2000-12-01')
    open(f, 'wb').write(urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'sat2js'}), timeout=300).read())
src = Image.open(f).convert('RGB'); assert src.size == (W, H), src.size
a = np.asarray(src, np.float32) / 255
lum = a.mean(axis=2); water = ((a[:, :, 2] > a[:, :, 0] * 1.3) & (a[:, :, 2] > a[:, :, 1] * 1.04) & (lum < 0.36)) | (lum < 0.105) | ((a[:, :, 2] > a[:, :, 0] * 1.1) & (a[:, :, 2] > a[:, :, 1] * 0.98) & (lum < 0.2))          # blue above red and green: dark green fields are not water
# the fill is done at a quarter of the size (the sea is a thousand pixels wide) and laid back under the water mask, grown a little for mixed shore pixels
q = 4; small = np.asarray(src.resize((W // q, H // q), Image.BILINEAR), np.float32) / 255
m = water.reshape(H // q, q, W // q, q).any(axis=(1, 3))
for _ in range(2): p = np.pad(m, 1, mode='edge'); m = p[:-2, 1:-1] | p[2:, 1:-1] | p[1:-1, :-2] | p[1:-1, 2:] | m
img = small.copy(); todo = m.copy(); n = 0
while todo.any() and n < 900:
    n += 1; P = np.pad(img, ((1, 1), (1, 1), (0, 0)), mode='edge'); K = np.pad(~todo, 1, mode='constant').astype(np.float32)
    s = np.zeros_like(img); c = np.zeros(todo.shape, np.float32)
    for dy, dx in ((0, 1), (2, 1), (1, 0), (1, 2)):
        k = K[dy:dy + todo.shape[0], dx:dx + todo.shape[1]]; s += P[dy:dy + todo.shape[0], dx:dx + todo.shape[1]] * k[:, :, None]; c += k
    hit = todo & (c > 0); img[hit] = s[hit] / c[hit][:, None]; todo = todo & ~hit
fill = np.asarray(Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8), 'RGB').filter(ImageFilter.GaussianBlur(2)).resize((W, H), Image.BILINEAR), np.float32) / 255
mk = np.asarray(Image.fromarray((m * 255).astype(np.uint8)).resize((W, H), Image.BILINEAR).filter(ImageFilter.GaussianBlur(3)), np.float32)[:, :, None] / 255
mk = np.clip(mk * 2.0, 0, 1); full = a * (1 - mk) + fill * mk
out = Image.fromarray((np.clip(full, 0, 1) * 255).astype(np.uint8), 'RGB')
buf = io.BytesIO(); out.save(buf, 'JPEG', quality=80)
open(os.path.join(ROOT, 'src', 'sat.js'), 'w').write("// Generated by tools/sat2js.py from the NASA / USGS Landsat WELD composite of 2000 (public domain). Never hand-edit.\nconst SAT_JPG = 'data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode() + "';\n")
img = full
out.save(os.path.join(CACHE, 'filled.png')); print('water pixels', int(m.sum()), 'fill rings', n, 'jpeg', len(buf.getvalue()) // 1024, 'KB', 'mean colour', [round(float(v), 3) for v in img.reshape(-1, 3).mean(axis=0)])
