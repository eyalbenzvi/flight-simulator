#!/usr/bin/env python3
"""The real colour of the land, coarse: NASA's Blue Marble Next Generation (public domain, about 500 m a pixel) over the map window -> src/sat.js.

The terrain shader uses it as the ground's base tint under all its own detail, so deserts, hills and plains have their true hues and patterns. Water
pixels (the sea, the two lakes) are filled from the nearest land, so no blue bleeds onto the shore where the game's coast differs from the real one.

  python3 tools/sat2js.py
"""
import base64, io, os, urllib.request
import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); CACHE = os.path.join(ROOT, 'raw', 'sat'); os.makedirs(CACHE, exist_ok=True)
f = os.path.join(CACHE, 'bluemarble.jpg')
if not os.path.exists(f):
    url = ('https://gibs.earthdata.nasa.gov/wms/epsg4326/best/wms.cgi?SERVICE=WMS&REQUEST=GetMap&VERSION=1.3.0&LAYERS=BlueMarble_NextGeneration'
           '&CRS=EPSG:4326&BBOX=29.2,33.6,33.6,36.4&WIDTH=512&HEIGHT=1024&FORMAT=image/jpeg')
    open(f, 'wb').write(urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'sat2js'}), timeout=120).read())
a = np.asarray(Image.open(f).convert('RGB'), np.float32) / 255
lum = a.mean(axis=2); water = (lum < 0.16) | ((a[:, :, 2] > a[:, :, 0] * 1.15) & (lum < 0.30)) | ((a[:, :, 1] > a[:, :, 0] * 1.25) & (lum < 0.28))
# grow the water mask a little (mixed shore pixels), then fill it from the land around, ring by ring
m = water.copy()
for _ in range(2): p = np.pad(m, 1, mode='edge'); m = p[:-2, 1:-1] | p[2:, 1:-1] | p[1:-1, :-2] | p[1:-1, 2:] | m
img = a.copy(); todo = m.copy(); n = 0
while todo.any() and n < 600:
    n += 1; P = np.pad(img, ((1, 1), (1, 1), (0, 0)), mode='edge'); K = np.pad(~todo, 1, mode='constant').astype(np.float32)
    s = np.zeros_like(img); c = np.zeros(todo.shape, np.float32)
    for dy, dx in ((0, 1), (2, 1), (1, 0), (1, 2)):
        k = K[dy:dy + todo.shape[0], dx:dx + todo.shape[1]]; s += P[dy:dy + todo.shape[0], dx:dx + todo.shape[1]] * k[:, :, None]; c += k
    hit = todo & (c > 0); img[hit] = s[hit] / c[hit][:, None]; todo = todo & ~hit
out = Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8), 'RGB').filter(ImageFilter.GaussianBlur(1.2))
buf = io.BytesIO(); out.save(buf, 'JPEG', quality=84)
open(os.path.join(ROOT, 'src', 'sat.js'), 'w').write("// Generated by tools/sat2js.py from NASA Blue Marble Next Generation (public domain). Never hand-edit.\nconst SAT_JPG = 'data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode() + "';\n")
out.save(os.path.join(CACHE, 'filled.png')); print('water pixels', int(m.sum()), 'fill rings', n, 'jpeg', len(buf.getvalue()) // 1024, 'KB', 'mean colour', [round(float(v), 3) for v in img.reshape(-1, 3).mean(axis=0)])
