#!/usr/bin/env python3
"""Real elevations for the terrain: public "terrarium" elevation tiles (Mapzen / AWS Open Data: SRTM on land, GEBCO at sea) -> src/dem.js.

Fetches the zoom-9 tiles over the map window (about 300 m a pixel here) into raw/dem/, averages them onto a grid of 0.00625 degrees (449 x 705 samples,
about 600 x 700 m of real ground, the scale of the terrain mesh), smooths lightly, and writes the grid as a 16-bit PNG (R high byte, G low byte of
height + 1000 m, clamped to -600 m at sea) in a data URL: DEM_PNG, read by rawHeight() in src/01-geography.js.

  python3 tools/dem2js.py
"""
import base64, io, math, os, sys, urllib.request
import numpy as np
from PIL import Image

LON0, LON1, LAT0, LAT1, STEP, Z = 33.6, 36.4, 29.2, 33.6, 0.00625, 9
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); CACHE = os.path.join(ROOT, 'raw', 'dem'); os.makedirs(CACHE, exist_ok=True)
n = 2 ** Z
tx = lambda lon: (lon + 180) / 360 * n
ty = lambda lat: (1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n
x0, x1, y0, y1 = int(tx(LON0)), int(tx(LON1)), int(ty(LAT1)), int(ty(LAT0))
big = np.zeros(((y1 - y0 + 1) * 256, (x1 - x0 + 1) * 256), np.float32)
for y in range(y0, y1 + 1):
    for x in range(x0, x1 + 1):
        f = os.path.join(CACHE, f'{Z}_{x}_{y}.png')
        if not os.path.exists(f):
            url = f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{Z}/{x}/{y}.png'
            req = urllib.request.Request(url, headers={'User-Agent': 'dem2js'})
            open(f, 'wb').write(urllib.request.urlopen(req, timeout=60).read())
        a = np.asarray(Image.open(f).convert('RGB'), np.float32)
        big[(y - y0) * 256:(y - y0 + 1) * 256, (x - x0) * 256:(x - x0 + 1) * 256] = a[:, :, 0] * 256 + a[:, :, 1] + a[:, :, 2] / 256 - 32768
print('tiles', (x1 - x0 + 1) * (y1 - y0 + 1), 'mosaic', big.shape, 'range', big.min(), big.max())
W, H = round((LON1 - LON0) / STEP) + 1, round((LAT1 - LAT0) / STEP) + 1
out = np.zeros((H, W), np.float32)
half = STEP / 2
for j in range(H):
    lat = LAT1 - j * STEP
    pa, pb = (ty(lat + half) - y0) * 256, (ty(lat - half) - y0) * 256
    r0, r1 = max(0, int(pa)), min(big.shape[0], max(int(pa) + 1, int(math.ceil(pb))))
    rows = big[r0:r1].mean(axis=0)
    for i in range(W):
        lon = LON0 + i * STEP
        ca, cb = (tx(lon - half) - x0) * 256, (tx(lon + half) - x0) * 256
        c0, c1 = max(0, int(ca)), min(big.shape[1], max(int(ca) + 1, int(math.ceil(cb))))
        out[j, i] = rows[c0:c1].mean()
# a light blur (1-2-1 in both directions, once): single-sample spikes would stand four times as steep on the compressed map
p = np.pad(out, 1, mode='edge'); out = (p[:-2, :-2] + p[:-2, 2:] + p[2:, :-2] + p[2:, 2:] + 2 * (p[:-2, 1:-1] + p[2:, 1:-1] + p[1:-1, :-2] + p[1:-1, 2:]) + 4 * p[1:-1, 1:-1]) / 16
np.save(os.path.join(CACHE, 'grid.npy'), out)
v = np.clip(np.round(out + 1000), 400, 65535).astype(np.uint16)
img = np.zeros((H, W, 3), np.uint8); img[:, :, 0] = v >> 8; img[:, :, 1] = v & 255
buf = io.BytesIO(); Image.fromarray(img, 'RGB').save(buf, 'PNG', optimize=True)
js = ("// Generated by tools/dem2js.py from public elevation tiles (SRTM / GEBCO). Never hand-edit.\n"
      f"const DEM_INFO = {{ lon0: {LON0}, lat1: {LAT1}, step: {STEP}, w: {W}, h: {H} }};\n"
      "const DEM_PNG = 'data:image/png;base64," + base64.b64encode(buf.getvalue()).decode() + "';\n")
open(os.path.join(ROOT, 'src', 'dem.js'), 'w').write(js)
print('grid', W, 'x', H, 'png', len(buf.getvalue()) // 1024, 'KB', 'heights', round(float(out.min())), 'to', round(float(out.max())))
