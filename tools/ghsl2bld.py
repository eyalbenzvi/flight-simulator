"""Step 2 of the data pipeline (run from the repository root): turns the two GHSL tiles into src/data.js and data/buildings.png.
Needs data/estimate.png and data/locs.json from tools/make_estimate.py."""
import numpy as np, rasterio, json, math, io, base64, re
from rasterio.warp import transform
from PIL import Image
KX, KZ, CELL = 23750, 27700, 60
X0, Z0 = (33.6 - 35) * KX, -(33.6 - 31.4) * KZ
W, H = math.ceil((36.4 - 33.6) * KX / CELL), math.ceil((33.6 - 29.2) * KZ / CELL)
S = rasterio.open('raw/GHS_BUILT_S_E2020_GLOBE_R2023A_54009_100_V1_0_R6_C22.tif'); Hh = rasterio.open('raw/GHS_BUILT_H_ANBH_E2018_GLOBE_R2023A_54009_100_V1_0_R6_C22.tif')
bs = S.read(1).astype(np.float32); bh = Hh.read(1); bs[bs == 65535] = 0; bh[bh < 0] = 0
cov = np.zeros((H, W), np.float32); hsum = np.zeros((H, W), np.float32); valid = np.zeros((H, W), bool)
# each 60 m game block is 240 m of real ground: sample it on a 3x3 grid of real 80 m steps
ii, jj = np.meshgrid(np.arange(W), np.arange(H))
for dy in (-1, 0, 1):
    for dx in (-1, 0, 1):
        x = X0 + (ii + 0.5 + dx / 3) * CELL; z = Z0 + (jj + 0.5 + dy / 3) * CELL
        lon = (x / KX + 35).ravel(); lat = (31.4 - z / KZ).ravel()
        mx, my = transform('EPSG:4326', S.crs, lon, lat); mx = np.array(mx); my = np.array(my)
        c = np.floor((mx - S.bounds.left) / 100).astype(int); r = np.floor((S.bounds.top - my) / 100).astype(int)
        ok = (c >= 0) & (c < S.width) & (r >= 0) & (r < S.height); v = np.zeros(lon.size, np.float32); hv = np.zeros(lon.size, np.float32)
        v[ok] = bs[r[ok], c[ok]]; hv[ok] = bh[r[ok], c[ok]]
        cov += (v / 10000).reshape(H, W) / 9; hsum += (v * hv).reshape(H, W); valid |= ok.reshape(H, W)
wsum = cov * 9 * 10000; hgt = np.where(wsum > 0, hsum / np.maximum(wsum, 1), 0)
print('valid rows', valid.any(axis=1).sum(), 'of', H, 'cov>0.06', (cov > 0.06).sum(), 'cov>0.1', (cov > 0.1).sum(), 'cov>0.15', (cov > 0.15).sum())
print('height percentiles where built', np.percentile(hgt[cov > 0.1], [5, 25, 50, 75, 95, 99, 99.9]).round(1))
# style from the nearest locality (CBS list): Arab towns and Jerusalem in stone, small Jewish localities with red roofs; beyond the list (West Bank cities, Gaza, Jordan) stone
L = json.load(open('raw/localities.json')); P = []
for l in L:
    c = (l.get('coordinates') or {}).get('wgs84')
    if not c: continue
    t = l.get('typeOfLocality') or {}; arab = 'לא יהוד' in (t.get('form') or '') + (t.get('group') or ''); pop = l.get('population') or 300
    P.append(((c['longitude'] - 35) * KX, -(c['latitude'] - 31.4) * KZ, 2 if (arab or l['id'] == 3000) else (3 if pop < 8000 else 1), 250 + 55 * math.sqrt(pop / 1000) * 10 ** 0.5))
P = np.array(P, np.float32)
TH = 0.07; ys, xs = np.nonzero((cov > TH) & valid); print('cells', len(ys))
cx = X0 + (xs + 0.5) * CELL; cz = Z0 + (ys + 0.5) * CELL; style = np.full(len(ys), 2, np.uint8)
for a in range(0, len(ys), 20000):
    d = np.hypot(cx[a:a + 20000, None] - P[None, :, 0], cz[a:a + 20000, None] - P[None, :, 1]) - P[None, :, 3]; k = d.argmin(1); near = d[np.arange(len(k)), k] < 700
    style[a:a + 20000] = np.where(near, P[k, 2].astype(np.uint8), 2)
rng = np.random.default_rng(11); rnd = rng.random(len(ys)); seed = rng.integers(0, 256, len(ys))
c0 = cov[ys, xs]; h0 = hgt[ys, xs]
h = np.clip(h0 * (0.75 + 0.6 * rnd), 4, 250)
tower = (h0 >= 13.5) & (rng.random(len(ys)) < 0.10); h = np.where(tower, np.clip(h0 * (2.2 + 2.5 * rng.random(len(ys))), 45, 190), h)
st = style.copy(); st[(st == 3) & ((h > 8.5) | (c0 > 0.3))] = 1; st[(st == 1) & (h < 6.5) & (c0 < 0.22)] = 3; st[(st == 1) & (h > 55)] = 4
size = np.clip(((c0 - TH) / 0.33 * 4).astype(int), 0, 3)
img = np.zeros((H, W, 4), np.uint8); img[ys, xs, 0] = h.astype(np.uint8); img[ys, xs, 1] = st | (size << 3); img[ys, xs, 2] = seed; img[ys, xs, 3] = 255
# the tile ends near latitude 33.1: north of it keep the earlier estimate
old = np.array(Image.open('data/estimate.png').convert('RGBA')); nv = ~valid; keep = nv & (old[:, :, 3] > 0); old[:, :, 1] |= (2 << 3); img[keep] = old[keep]
print('kept from estimate (north of the tile):', keep.sum(), 'styles', np.bincount(img[:, :, 1][img[:, :, 3] > 0] & 7), 'towers', int(tower.sum()))
buf = io.BytesIO(); Image.fromarray(img, 'RGBA').save(buf, 'PNG', optimize=True); b = buf.getvalue(); open('data/buildings.png', 'wb').write(b); print('png', len(b))
HEAD = """// ---------- 0. Settlement data ----------
// GENERATED by tools/ghsl2bld.py - do not edit by hand.
// BLD_PNG: one pixel per 60 m game block (240 m of real ground), from the EU's GHSL satellite layers: built-up surface 2020 (GHS-BUILT-S) and average building height 2018 (GHS-BUILT-H ANBH).
// R = height in metres, G = style (bits 0-2) and footprint size (bits 3-4), B = random seed. North of latitude 33.1 (outside the tile) it falls back to an estimate from the CBS localities list.
// LOCS: [Hebrew, English, lon, lat, population in thousands]
"""
open('src/data.js', 'w', encoding='utf8').write("'use strict';\n" + HEAD + 'const BLD_PNG = "data:image/png;base64,' + base64.b64encode(b).decode() + '";\nconst LOCS = ' + open('data/locs.json', encoding='utf8').read().strip() + ';\n')
pal = {1: (230, 230, 230), 2: (230, 200, 140), 3: (230, 90, 70), 4: (120, 200, 255)}; pv = np.full((H, W, 3), (20, 30, 40), np.uint8)
for k, c in pal.items(): pv[(img[:, :, 3] > 0) & ((img[:, :, 1] & 7) == k)] = c
px = lambda lon: int(((lon - 35) * KX - X0) / CELL); py = lambda lat: int((-(lat - 31.4) * KZ - Z0) / CELL)
Image.fromarray(pv[py(32.35):py(31.6), px(34.6):px(35.4)]).resize((1000, 1090), Image.NEAREST).save('data/preview.png')
